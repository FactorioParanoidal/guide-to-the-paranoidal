"""Assemble the guide into one page: index.html (next to assets/).

Usage (from the guide folder):
    python -I tools/build.py            # build index.html
    python -I tools/build.py --check    # build, then run tools/check.py
    python -I tools/build.py --single   # also write the one-file release dist/Guide_to_the_Paranoidal.html (tools/release.py)

Sources:
    src/page.html              page shell with placeholders  <!--@CSS-->  <!--@SECTIONS-->  <!--@JS-->  <!--@STATS-->  <!--@META-->
    src/sections.json          ordered chapter registry (id, file, titles, status)
    src/sections/*.html        chapter fragments (bilingual)
    src/css/*.css              styles, concatenated in file-name order
    src/js/core.js, src/js/widgets/*.js   scripts, core first, widgets in file-name order
    data/stats.json, data/names.json      generated by tools/extract_stats.py

Section micro-syntax (expanded here, so fragments stay short):
    <ru>текст</ru><en>text</en>          -> <span lang="ru">..</span><span lang="en">..</span>
    {{n:counts.items_visible}}           -> animated number from stats.json (any dotted path; len() via '#': {{n:#records.turrets}};
                                            list element by id via '@': {{n:records.ways.@angels-slag.produced_by}})
    {{icon:item/iron-plate}}             -> inline game icon with RU/EN tooltip (type/name as in the dump)
    {{icon-lg:technology/rocket-silo}}   -> large icon
    {{sprite:boiler}}                    -> entity sprite (assets/sprites/<key>.webp)
    {{fmt:records.boilers.0.effectivity|pct}}  -> formatted value: pct, int, mw, kj, raw
Everything else is plain HTML.
"""
import argparse, base64, glob, html, json, os, re, subprocess, sys, time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, 'src')

ap = argparse.ArgumentParser()
ap.add_argument('--check', action='store_true')
ap.add_argument('--only', help='comma list of section ids (preview build; writes _preview.html, ignores missing files)')
ap.add_argument('--single', nargs='?', const=os.path.join(ROOT, 'dist', 'Guide_to_the_Paranoidal.html'), metavar='OUT',
                help='also write the one-file guide (every asset embedded; default dist/Guide_to_the_Paranoidal.html)')
args = ap.parse_args()

stats = json.load(open(os.path.join(ROOT, 'data', 'stats.json'), encoding='utf-8'))
names = json.load(open(os.path.join(ROOT, 'data', 'names.json'), encoding='utf-8'))
registry = json.load(open(os.path.join(SRC, 'sections.json'), encoding='utf-8'))
problems = []

def lookup(path):
    count = path.startswith('#')
    if count:
        path = path[1:]
    cur = stats
    for part in path.split('.'):
        if isinstance(cur, list):
            if part.startswith('@'):  # element of a record list by its id: records.ways.@angels-slag.produced_by
                cur = [x for x in cur if isinstance(x, dict) and x.get('id') == part[1:]][0]
            else:
                cur = cur[int(part)]
        else:
            cur = cur[part]
    return len(cur) if count else cur

def icon_key(typ, name):
    return re.sub(r'[^A-Za-z0-9_.-]', '_', typ + '__' + name)

def fmt_value(v, kind):
    if kind == 'pct':
        return '%g%%' % round(v * 100, 1)
    if kind == 'int':
        return str(int(round(v)))
    if kind == 'mw':
        return '%g' % round(v / 1e6, 2)
    if kind == 'kj':
        return '%g' % round(v, 1)
    return str(v)

def expand(text, fname):
    def num(m):
        try:
            v = lookup(m.group(1))
        except Exception:
            problems.append('%s: unknown stat %s' % (fname, m.group(1)))
            return '<b class="num">?</b>'
        return '<b class="num" data-v="%s">%s</b>' % (v, v)
    text = re.sub(r'\{\{n:([^}]+)\}\}', num, text)

    def fmt(m):
        path, _, kind = m.group(1).partition('|')
        try:
            return fmt_value(lookup(path), kind)
        except Exception:
            problems.append('%s: unknown stat %s' % (fname, path))
            return '?'
    text = re.sub(r'\{\{fmt:([^}]+)\}\}', fmt, text)

    def icon(m):
        size = m.group(1)
        typ, _, name = m.group(2).partition('/')
        k = icon_key(typ, name)
        if not os.path.exists(os.path.join(ROOT, 'assets', 'icons', k + '.webp')):
            # tolerate a wrong item subtype (item vs tool/module/item-with-entity-data...)
            alt = glob.glob(os.path.join(ROOT, 'assets', 'icons', '*__' + icon_key('', name)[2:] + '.webp'))
            if alt:
                k = os.path.basename(alt[0])[:-5]
            else:
                problems.append('%s: missing icon %s (add it to tools/assets-config.json "icons" and run collect_assets.py)' % (fname, m.group(2)))
        nm = names.get(k, {'ru': name, 'en': name})
        cls = 'ic' if not size else 'ic ic-lg'
        return '<img class="%s" src="assets/icons/%s.webp" alt="" data-ru="%s" data-en="%s" loading="lazy">' % (
            cls, k, html.escape(nm['ru'], True), html.escape(nm['en'], True))
    text = re.sub(r'\{\{icon(-lg)?:([^}]+)\}\}', icon, text)

    def sprite(m):
        k, _, extra = m.group(1).partition('|')
        if not os.path.exists(os.path.join(ROOT, 'assets', 'sprites', k + '.webp')):
            problems.append('%s: missing sprite %s' % (fname, k))
        nm = names.get('sprite:' + k, {'ru': k, 'en': k})
        return '<img class="sprite %s" src="assets/sprites/%s.webp" alt="" data-ru="%s" data-en="%s" loading="lazy">' % (
            extra, k, html.escape(nm['ru'], True), html.escape(nm['en'], True))
    text = re.sub(r'\{\{sprite:([^}]+)\}\}', sprite, text)

    text = re.sub(r'<ru>', '<span lang="ru">', text)
    text = re.sub(r'<en>', '<span lang="en">', text)
    text = re.sub(r'</(ru|en)>', '</span>', text)
    leftovers = re.findall(r'\{\{[^}]*\}\}', text)
    for x in leftovers:
        problems.append('%s: unexpanded %s' % (fname, x))
    return text

# ---------------------------------------------------------------- self-links
# A link that leads to where the reader already is gets unwrapped to plain text (user rule):
#  - a link to an id inside the same h3 block (or to the h3 itself, or to its own chapter);
#  - a glossary link to a term that is the topic of the block (term stem found in the h3 title), e.g. "slag" under "Slag: ...".
def _plain(h):
    return re.sub(r'<[^>]+>', ' ', h).lower()
_gloss_src = open(os.path.join(SRC, 'sections', '21-glossary.html'), encoding='utf-8').read()
GLOSS_STEMS = {}
for m in re.finditer(r'<dt id="(g-[^"]+)">(.*?)</dt>', _gloss_src, re.S):
    words = re.findall(r'[\w-]+', _plain(m.group(2)))
    GLOSS_STEMS[m.group(1)] = {w[:max(4, len(w) - 2)] for w in words if len(w) >= 4}
UNSELFED = []
def unself(raw, chapter_id):
    if chapter_id == 'glossary':
        return raw
    out = []
    for blk in re.split(r'(?=<h3 )', raw):
        ids = set(re.findall(r'id="([^"]+)"', blk)) | {chapter_id}
        h3 = re.match(r'<h3[^>]*>(.*?)</h3>', blk, re.S)
        title = _plain(h3.group(1)) if h3 else ''
        def fix(m):
            target, text = m.group(1), m.group(2)
            topic = target in GLOSS_STEMS and title and any(st in title for st in GLOSS_STEMS[target])
            if target in ids or topic:
                UNSELFED.append('%s #%s' % (chapter_id, target))
                return text
            return m.group(0)
        out.append(re.sub(r'<a class="x[^"]*" href="#([^"]+)">(.*?)</a>', fix, blk, flags=re.S))
    return ''.join(out)

# ---------------------------------------------------------------- sections
parts = []
for entry in registry['sections']:
    if entry.get('status') == 'disabled':
        continue
    if args.only and entry['id'] not in args.only.split(','):
        continue
    path = os.path.join(SRC, 'sections', entry['file'])
    if not os.path.exists(path):
        problems.append('missing section file %s' % entry['file'])
        continue
    raw = open(path, encoding='utf-8').read()
    if 'id="%s"' % entry['id'] not in raw:
        problems.append('%s: no element with id="%s"' % (entry['file'], entry['id']))
    raw = unself(raw, entry['id'])
    parts.append('\n<!-- ===== section: %s (%s) ===== -->\n' % (entry['id'], entry['file']) + expand(raw, entry['file']))

css = '\n'.join('/* ---- %s ---- */\n' % os.path.basename(f) + open(f, encoding='utf-8').read()
                for f in sorted(glob.glob(os.path.join(SRC, 'css', '*.css'))))
js_files = [os.path.join(SRC, 'js', 'core.js')] + sorted(glob.glob(os.path.join(SRC, 'js', 'widgets', '*.js')))
js = '\n'.join('/* ---- %s ---- */\n' % os.path.relpath(f, SRC).replace('\\', '/') + open(f, encoding='utf-8').read() for f in js_files)

meta = {
    'built': time.strftime('%Y-%m-%d %H:%M'),
    'guide_version': registry.get('guide_version'),
    'data': stats['meta'],
    'sections': [{k: e.get(k) for k in ('id', 'ru', 'en', 'icon', 'achievement_ru', 'achievement_en')} for e in registry['sections'] if e.get('status') != 'disabled'],
}
# reader achievements declared inside widgets: G.achieve('id', 'ru', 'en', <icon expr>, 'desc ru', 'desc en')
ach = []
for m in re.finditer(r"G\.achieve\('([\w-]+)', '([^']*)', '([^']*)', ([^,]+(?:\([^)]*\))?), '([^']*)', '([^']*)'\)", js):
    icon_expr = m.group(4).strip()
    km = re.match(r"G\.icon\('([^']+)'\)", icon_expr)
    ka = re.match(r"G\.asset\('([^']+)'\)", icon_expr)
    icon = ('assets/icons/%s.webp' % km.group(1) if km else ka.group(1) if ka else
            icon_expr.strip("'") if icon_expr.startswith("'") else 'assets/icons/technology__automation.webp')
    if m.group(1) not in [a['id'] for a in ach]:
        ach.append({'id': m.group(1), 'ru': m.group(2), 'en': m.group(3), 'icon': icon, 'dru': m.group(5), 'den': m.group(6)})
meta['widget_achievements'] = ach
stats_out = dict(stats)
stats_out['meta'] = meta
cpath = os.path.join(ROOT, 'data', 'icon-colors.json')
stats_out['icon_colors'] = json.load(open(cpath, encoding='utf-8')) if os.path.exists(cpath) else {}

page = expand(open(os.path.join(SRC, 'page.html'), encoding='utf-8').read(), 'page.html')  # shell only; CSS/JS are inserted verbatim
# the version is read by the Paranoidal Launcher from the first bytes of the one-file guide: keep it right after <meta charset>
if '<meta charset="utf-8">' not in page:
    problems.append('page.html: no <meta charset="utf-8">')
page = page.replace('<meta charset="utf-8">', '<meta charset="utf-8">\n<meta name="guide-version" content="%s">' % meta['guide_version'], 1)
page = page.replace('<!--@CSS-->', '<style>\n' + css + '\n</style>')
page = page.replace('<!--@SECTIONS-->', '\n'.join(parts))
page = page.replace('<!--@STATS-->', '<script id="guide-data" type="application/json">' +
                    json.dumps(stats_out, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/') + '</script>')
page = page.replace('<!--@JS-->', '<script>\n' + js + '\n</script>')
page = page.replace('<!--@META-->', 'built %s · guide %s · data %s (%s)' % (meta['built'], meta['guide_version'], stats['meta'].get('dump'), stats['meta'].get('generated')))

# ---------------------------------------------------------------- one-file guide
# The same page with every asset inside, for the Paranoidal Launcher and offline reading (no assets/ folder next to it).
#  - CSS url(assets/..) and the favicon become data: URLs (each file is used once or twice there);
#  - every other asset file is stored once in <script id="guide-assets"> (path -> base64); window.GuideAssets(path)
#    turns it into a blob: URL on first use, so an icon shown a hundred times is decoded and kept once;
#  - src/href="assets/.." attributes of the markup become data-asset-src/-href and are resolved before core.js runs,
#    data-icon="assets/.." is resolved in place; JS builds its paths through G.asset()/G.icon() (check.py enforces it).
MIME = {'.webp': 'image/webp', '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.gif': 'image/gif',
        '.svg': 'image/svg+xml', '.ttf': 'font/ttf', '.woff2': 'font/woff2'}
SHIM = r"""<script>
/* one-file guide: assets embedded by tools/build.py --single */
(function () {
  var A = JSON.parse(document.getElementById('guide-assets').textContent), U = {};
  window.GuideAssets = function (p) {
    if (U[p]) return U[p];
    var a = A[p];
    if (!a) return p;
    var bin = atob(a[1]), u8 = new Uint8Array(bin.length);
    for (var i = 0; i < bin.length; i++) u8[i] = bin.charCodeAt(i);
    return (U[p] = URL.createObjectURL(new Blob([u8], { type: a[0] })));
  };
  [['data-asset-src', 'src'], ['data-asset-href', 'href']].forEach(function (x) {
    document.querySelectorAll('[' + x[0] + ']').forEach(function (e) { e.setAttribute(x[1], window.GuideAssets(e.getAttribute(x[0]))); e.removeAttribute(x[0]); });
  });
  document.querySelectorAll('[data-icon^="assets/"]').forEach(function (e) { e.setAttribute('data-icon', window.GuideAssets(e.getAttribute('data-icon'))); });
})();
</script>
"""

def asset_bytes(rel):
    path = os.path.join(ROOT, *rel.split('/'))
    if not os.path.isfile(path):
        problems.append('single: missing asset %s' % rel)
        return None, None
    mime = MIME.get(os.path.splitext(rel)[1].lower())
    if not mime:
        problems.append('single: unknown asset type %s' % rel)
        return None, None
    return mime, open(path, 'rb').read()

def data_url(rel):
    mime, data = asset_bytes(rel)
    return rel if data is None else 'data:%s;base64,%s' % (mime, base64.b64encode(data).decode('ascii'))

def make_single(page):
    cut = page.index('<script id="guide-data"')
    body, tail = page[:cut], page[cut:]
    css_refs = set(re.findall(r'url\((assets/[^)"\']+)\)', body))
    body = re.sub(r'url\((assets/[^)"\']+)\)', lambda m: 'url("%s")' % data_url(m.group(1)), body)
    body = re.sub(r'(<link rel="icon" href=")(assets/[^"]+)"', lambda m: m.group(1) + data_url(m.group(2)) + '"', body)
    body = re.sub(r'(?<![-\w])(src|href)="(assets/[^"]+)"', r'data-asset-\1="\2"', body)
    # every asset file except fonts/backgrounds that only CSS uses (already inlined above)
    files = []
    for sub in ('icons', 'sprites', 'static'):
        for dirpath, _, names in os.walk(os.path.join(ROOT, 'assets', sub)):
            for n in names:
                rel = os.path.relpath(os.path.join(dirpath, n), ROOT).replace('\\', '/')
                if os.path.splitext(n)[1].lower() in MIME:
                    files.append(rel)
    rest = body.replace('url(', '') + tail
    table = {}
    for rel in sorted(files):
        if rel in css_refs and rel not in rest:
            continue
        mime, data = asset_bytes(rel)
        if data is not None:
            table[rel] = [mime, base64.b64encode(data).decode('ascii')]
    js_at = tail.index('<script>\n/* ---- js/core.js')
    blob = '<script id="guide-assets" type="application/json">' + json.dumps(table, separators=(',', ':')) + '</script>\n'
    single = body + tail[:js_at] + blob + SHIM + tail[js_at:]
    left = re.findall(r'(?<![-\w])(?:src|href)="assets/|url\(assets/', single)
    if left:
        problems.append('single: %d asset references left outside the embedded table' % len(left))
    return single, len(table)

out = os.path.join(ROOT, '_preview.html' if args.only else 'index.html')
open(out, 'w', encoding='utf-8', newline='\n').write(page)
print('self-links unwrapped: %d' % len(UNSELFED))
print('index.html: %d KB, %d sections, %d problems' % (len(page.encode('utf-8')) // 1024, len(parts), len(problems)))
if args.single and not args.only:
    single, n_assets = make_single(page)
    sout = os.path.abspath(args.single)
    os.makedirs(os.path.dirname(sout), exist_ok=True)
    open(sout, 'w', encoding='utf-8', newline='\n').write(single)
    print('%s: %.1f MB, %d embedded assets, %d problems' % (os.path.basename(sout), len(single.encode('utf-8')) / 1048576, n_assets, len(problems)))
for p in problems:
    print('  !', p)
if args.check:
    r = subprocess.call([sys.executable, '-I', os.path.join(HERE, 'check.py')])
    sys.exit(r or (1 if problems else 0))
sys.exit(1 if problems else 0)
